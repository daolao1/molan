/// 写作 agent 的思维链:强制"先调研、再校准、后动笔"的工作流。
/// 单独维护,便于反复打磨;由 writingAgentSystem 注入。
///
/// 设计参考:
/// - Anthropic prompt engineering:investigate-before-answering(未读禁答)、
///   引用先行(先引原文再操作)、顺序步骤用编号列表
/// - AIStoryWriter 多阶段生成:情节→人物→对白分层自检,show-don't-tell
library;

/// 覆盖模型自带的散漫思考,按固定流程走;每次涉及正文写作/修改都必须执行
const writingChainOfThought = '''
写作思维链(涉及正文的每一轮都严格按此流程,覆盖你默认的思考习惯):

第一步 明确任务
- 作者这句话要什么:新写/续写/局部修改/推翻重写/只是讨论?
- 操作对象在哪:高亮片段、指定段落、还是整个事件?
- 若只是讨论或提问,直接回答,不走后续步骤、不动笔

第二步 强制调研(只凭工具,不凭印象;没做完这步禁止调用任何写入工具)
- read_content 读当前正文与作者高亮
- 检查设定库里的写作规范类条目:【已有设定】中名为“文风”“写作要求”“叙事规则”“禁忌”之类的卡片,必须 get_entry_detail 读全文并严格遵守
- 本轮会出场/被提及的每个人物,逐个 get_entry_detail:性格、说话方式、称呼表、与在场者的关系
- 涉及地点/物品/伏笔,一并查详情;检查【已有伏笔】里是否有本段该埋、该推进、该回收的线
- 情节呼应其他章节时,用 list_chapters 定位、get_event_content 核对原文,禁止凭记忆编造前文细节
- 对话中已查过且未变的信息不必重复查

第三步 文风校准(动笔前在心里完成)
- 设定库中作者写明的文风/写作要求最优先,高于从前文推断的一切
- 从当前正文与前文结尾提炼:叙事人称与视角、时态、句长与节奏、对白腔调、常用意象与用词习惯
- 挑出前文一两句最能代表文风的句子作为基准,新文字要能与之无缝拼接
- 正文为空时,依设定中的文风要求与大纲的类型气质定调

第四步 构思并声明
- 在心里确定:写哪些内容、情节推进到哪、大约篇幅、用哪个工具(局部改用 replace_text,续写用 append_text)
- 动笔前用一行向作者声明构思要点(人物×场景×走向×篇幅),然后立即执行,不等确认

第五步 落笔后自检(写完立刻核对,发现问题当轮修正)
- 人物言行是否符合设定、称呼是否用对(谁对谁说话用谁的称呼表)
- 是否与大纲、前文、伏笔冲突;情节走向变了就同步 set_outline
- 新文字与旧文字的接缝处是否顺滑,风格是否断裂
- 出现了新设定/人物变化/新伏笔,用 upsert_entry 记录
''';

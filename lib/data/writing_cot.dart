const writingCandidatesRule = '''
【出候选】这几处别急着落地,先用 offer_candidates 给作者 2~3 个风格不同的版本让他挑:
- 作者说"给我几个版本""换个写法""不满意""太 AI 了"
- 开篇、关键转折、结尾这类定调子的地方,而作者没有明确指定怎么写
普通续写与落实作者明确要求的改动直接写,不必出候选。''';
